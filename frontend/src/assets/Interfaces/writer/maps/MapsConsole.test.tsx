    await waitFor(() => expect(puts(backend)).toHaveLength(1))
    const [s] = lastPut(backend).symbols
    expect(s.kind).toBe('tree')
    expect(s.x).toBeCloseTo(3.25, 1)
    expect(s.y).toBeCloseTo(2.75, 1)
