  // Draw a line or region: choose its preset, click the points (in cells; each snaps to a grid corner or a cell centre), finish with Enter.
  async function draw(user: ReturnType<typeof userEvent.setup>, canvas: Element, preset: string, points: Array<[number, number]>, finishWith: 'enter' | 'double-click' = 'enter') {
    await user.click(screen.getByRole('button', { name: preset }))
    for (const [x, y] of points) pointer(canvas, 'pointerdown', at(x, y))
    if (finishWith === 'enter') fireEvent.keyDown(canvas, { key: 'Enter' })
    else fireEvent.doubleClick(canvas, at(...points[points.length - 1]))
  }
